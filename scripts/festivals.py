def _qingming(year):
    """清明落在 4/4 或 4/5，用通用的節氣公式推算。"""
    y = year % 100
    day = int(y * 0.2422 + 4.81) - (y - 1) // 4
    return datetime.date(year, 4, min(max(day, 4), 6))


def _mothers_day(year):
    """母親節是五月的第二個週日。"""
    d = datetime.date(year, 5, 1)
    d += datetime.timedelta(days=(6 - d.weekday()) % 7)  # 五月第一個週日
    return d + datetime.timedelta(days=7)


def get_festival(date=None):
    """回傳當天的節日名稱，沒有就回 None。

    同一天可能同時是兩個節日（例如兒童節碰上清明），會用頓號串起來。
    """
    d = date or datetime.date.today()
    if isinstance(d, datetime.datetime):
        d = d.date()

    names = []
    solar = _SOLAR_FESTIVALS.get(d.strftime("%m-%d"))
    if solar:
        names.append(solar)
    lunar = _LUNAR_FESTIVALS.get(d.isoformat())
    if lunar:
        names.append(lunar)
    if d == _qingming(d.year):
        names.append("清明節")
    if d == _mothers_day(d.year):
        names.append("母親節")

    # 去重但保留順序
    seen, uniq = set(), []
    for n in names:
        if n not in seen:
            seen.add(n)
            uniq.append(n)
    return "、".join(uniq) if uniq else None
